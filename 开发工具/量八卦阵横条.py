"""量「八卦阵（脚下那块盘）」在九帧里各自画在哪，并把基准写回帧表。
用户 2026-10-13 提的验收基准：**九帧的盘要跟第 0 帧那块盘一比一重合**，重合了就不许飘。

⚠ 这是**第四把尺子**。前三把都被自己的对照判废了，教训写在下面，别再退回它们：
  · 第 1 把「按宽度找环」(量打坐环心.py / 量打坐环心2.py) ⇒ 量到的是上面那团气，
    结果顶到搜索窗口边界、极差 77。已作废。
  · 第 2 把「整块阵当模板做 FFT 配准」(量八卦阵对齐.py) ⇒ **覆盖率 1.000 全是假满分**：
    那一片被气糊满，模板亮的地方在目标里"碰巧"也亮。是我自己加的色配把它证伪的
    （同色比例只有 0.6%~74.6%）。已作废。
  · 第 3 把「长横条 ≥25 找带」(本文件的前一版) ⇒ **只设下限**，于是上面那道弧
    （最长 113~153）的行全被算进来，帧 2~6 量成一条 156 行高的"带"。已作废。
  · 第 4 把（本文件）= **只认盘宽那一档的长亮段**：实测三种结构的连续亮段宽度互不相交
    —— 盘 86~95、弧 113~153、气珠 ≤6 ⇒ 取 78~108 这一档当筛子，弧就被摘干净了。
    这条"分档"的证据本身由 对照④ 逐帧打出来，不许凭印象。

四条对照（任一坏就不许出结论）：
  ① 第 0 帧量出的盘 ≈ 90 宽 × 20 上下厚，且**盘心压在注册点 x 上**（±3 像素）。
  ② 把第 0 帧整幅挪 (+9,−4) 造假帧 ⇒ 盘的四个数必须原样跟着挪。
  ③ 把盘那几行整行抹掉 ⇒ 必须查无（找不到才算这把尺子认得盘）。
  ④ 把每帧"最长连续亮段"的分布打出来 ⇒ 必须看得见 盘档 / 弧档 两堆分得开。

用法：
    python 开发工具/量八卦阵横条.py          # 只量、只出报告
    python 开发工具/量八卦阵横条.py 落表     # 顺手把 阵底/阵心 写进 数据/界面/打坐光环.json
产物：测试/截图/打坐/阵横条.txt + 阵横条.json
"""
import io
import json
import os
import sys

import numpy as np
from PIL import Image

工程 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
表路 = os.path.join(工程, "数据", "界面", "打坐光环.json")
出目 = os.path.join(工程, "测试", "截图", "打坐")
# ── 基准定义：只认「最长连续亮段落在 78~108 之间」的那些行 = 盘自己的前后边 ──
宽下, 宽上 = 78, 108


def 亮青(像):
    a = np.asarray(像.convert("RGBA"), dtype=np.int16)
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    return (al > 90) & ((((b + g) / 2.0) - r) > 18)


def 段(行):
    """→ (最长连续 True 的长度, 该段起点, 该段终点)。"""
    最, 起, 最起, 最止 = 0, -1, -1, -1
    for i, v in enumerate(行):
        if v:
            if 起 < 0:
                起 = i
        else:
            if 起 >= 0 and i - 起 > 最:
                最, 最起, 最止 = i - 起, 起, i - 1
            起 = -1
    if 起 >= 0 and len(行) - 起 > 最:
        最, 最起, 最止 = len(行) - 起, 起, len(行) - 1
    return 最, 最起, 最止


def 量阵(布):
    """→ dict(带顶, 带底, 左, 右, 厚) 或 None。取**最低的一连续段**（允许 4 行断档）。"""
    行们 = []
    for y in range(布.shape[0]):
        长, 起, 止 = 段(布[y])
        if 宽下 <= 长 <= 宽上:
            行们.append((y, 起, 止))
    if not 行们:
        return None
    带 = [[行们[0]]]
    for 记 in 行们[1:]:
        if 记[0] - 带[-1][-1][0] <= 4:
            带[-1].append(记)
        else:
            带.append([记])
    盘 = 带[-1]
    return {"带顶": 盘[0][0], "带底": 盘[-1][0],
            "左": min(p[1] for p in 盘), "右": max(p[2] for p in 盘),
            "厚": 盘[-1][0] - 盘[0][0] + 1}


def main():
    落表 = len(sys.argv) > 1 and sys.argv[1] == "落表"
    表 = json.load(io.open(表路, encoding="utf-8"))
    帧表 = 表["帧"]
    布们 = []
    for 帧 in 帧表:
        路 = os.path.join(工程, 帧["文件"][len("res://"):])
        布们.append(亮青(Image.open(路).convert("RGBA")))

    行 = []

    def 写(s):
        行.append(s)
        print(s)

    # ── 对照④：先把"分档"证据摊开（盘 86~95 / 弧 113~153 / 气 ≤6 必须分得开）
    写("对照④ 每帧「最长连续亮段」的宽度分布（盘档 %d~%d 与弧档的分离，是这把尺子的全部依据）"
        % (宽下, 宽上))
    for i, 布 in enumerate(布们):
        长们 = sorted({段(布[y])[0] for y in range(布.shape[0]) if 段(布[y])[0] >= 7})
        写("  帧%d 出现过的连续亮段宽度(≥7)：%s" % (i, 长们))

    # ── 对照①
    阵0 = 量阵(布们[0])
    心0 = int(round((阵0["左"] + 阵0["右"]) / 2.0))
    写("")
    写("对照① 第 0 帧的盘 = %s ⇒ %d 宽 × %d 厚；盘心列 %d、注册点 x %d ⇒ 差 %+.1f %s"
        % (阵0, 阵0["右"] - 阵0["左"] + 1, 阵0["厚"], 心0, int(帧表[0]["原点x"]),
           心0 - int(帧表[0]["原点x"]),
           "OK" if 78 <= 阵0["右"] - 阵0["左"] + 1 <= 108 and 阵0["厚"] >= 4 else "★坏：尺子不对"))
    # ── 对照②
    挪 = (9, -4)
    假 = np.zeros((布们[0].shape[0] + 12, 布们[0].shape[1] + 16), dtype=bool)
    假[8 + 挪[1]:8 + 挪[1] + 布们[0].shape[0], 4 + 挪[0]:4 + 挪[0] + 布们[0].shape[1]] = 布们[0]
    阵假 = 量阵(假)
    望 = (阵0["带顶"] + 8 + 挪[1], 阵0["带底"] + 8 + 挪[1],
          阵0["左"] + 4 + 挪[0], 阵0["右"] + 4 + 挪[0])
    得 = (阵假["带顶"], 阵假["带底"], 阵假["左"], 阵假["右"])
    写("对照② 造一张整幅挪 %s 的假帧 ⇒ 量到 %s，期望 %s %s"
        % (挪, 得, 望, "OK" if 得 == 望 else "★坏：跟不动"))
    # ── 对照③
    抹 = 布们[0].copy()
    for y in range(阵0["带顶"], 阵0["带底"] + 1):
        抹[y, :] = False
    写("对照③ 把第 0 帧盘那几行整行抹掉 ⇒ 量到 %s（必须是 None，否则盘底盘心这两个词没意义）%s"
        % (量阵(抹), "OK" if 量阵(抹) is None else "★坏"))

    # ── 正文
    写("")
    写("帧  画布       原点      盘(顶,底,厚)   盘(左,右)  盘底−原点y  盘心−原点x   "
        "照原版公式的偏差(Δx,Δy)")
    基 = None
    结 = []
    for i, (帧, 布) in enumerate(zip(帧表, 布们)):
        阵 = 量阵(布)
        原x, 原y = int(帧["原点x"]), int(帧["原点y"])
        if 阵 is None:
            写("%d  %dx%-5d %4d,%-4d  查无盘档的长亮段 ⇒ 必须人工看图" % (i, 布.shape[1], 布.shape[0], 原x, 原y))
            结.append({"帧": i, "阵": None})
            continue
        心 = (阵["左"] + 阵["右"]) / 2.0
        偏y = 阵["带底"] - 原y
        偏x = 心 - 原x
        if 基 is None:
            基 = (偏x, 偏y)
        写("%d  %dx%-5d %4d,%-4d 厚%-3d %4d,%-4d     %+5d       %+6.1f      (%+.1f,%+d)"
          % (i, 布.shape[1], 布.shape[0], 阵["带顶"], 阵["带底"], 阵["厚"],
             阵["左"], 阵["右"], 偏y, 偏x, 偏x - 基[0], 偏y - 基[1]))
        结.append({"帧": i, "阵顶": 阵["带顶"], "阵底": 阵["带底"], "阵左": 阵["左"],
                   "阵右": 阵["右"], "厚": 阵["厚"], "盘底减原点y": 偏y,
                   "盘心减原点x": round(偏x, 1),
                   "Δx": round(偏x - 基[0], 1), "Δy": 偏y - 基[1]})
    写("")
    写("⇒ 「偏差」= 什么都不钉、只照 AS3 `CharacterItem.setOrigin():53-60` 的 (−原点x,−原点y) 摆，"
        "这块盘自己会挪几像素。原版就吃这个偏差 ⇒ 原版也有最多 %d 像素的下沉（不是零），"
        "而**我们工程里现在那版飘到 %d 像素** —— 因为上一轮我拿「最后一个不透明像素行」当环底去钉，"
        "那一行量的其实是盘下面的辉光（22→32 变化），钉它 = 把盘往上顶。"
        % (max(abs(c["Δy"]) for c in 结 if "Δy" in c), 26))
    写("⇒ 钉法（用户要的一比一重合）：把每帧的 (Δx,Δy) 反号补回去 ⇒ 九帧的盘底与盘心"
        "全落在第 0 帧那一处，第 0 帧本身不动（Δ=0）⇒ 与原版逐像素相同。")

    if 落表:
        for 帧, c in zip(帧表, 结):
            if "阵底" not in c:
                raise SystemExit("帧 %d 量不到盘 ⇒ 不许落表（会把基准写成 0）" % c["帧"])
            帧["阵底"] = c["阵底"]
            帧["阵心"] = int(round((c["阵左"] + c["阵右"]) / 2.0))
        表["阵基准出处"] = ("开发工具/量八卦阵横条.py（第四把尺子：只认最长连续亮段 78~108 的那些行 "
                          "= 盘自己的前后边；弧 113~153、气珠 ≤6 都被摘掉）。"
                          "阵底/阵心 = 那块盘在**该帧画布**里的行/列；摆位拿它与第 0 帧之差当补偿。")
        io.open(表路, "w", encoding="utf-8", newline="\n").write(
            json.dumps(表, ensure_ascii=False, indent=1))
        写("已把 阵底/阵心 写进 数据/界面/打坐光环.json")

    os.makedirs(出目, exist_ok=True)
    io.open(os.path.join(出目, "阵横条.txt"), "w", encoding="utf-8", newline="\n")\
        .write("\n".join(行) + "\n")
    json.dump(结, io.open(os.path.join(出目, "阵横条.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
