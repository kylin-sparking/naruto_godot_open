# -*- coding: utf-8 -*-
"""定案用的最后一把尺子：**拿第 0 帧那块八卦阵的花纹当 RGB 模板，去每一帧里找它自己。**

为什么还要再来一把（前三把都在"找边"，都栽了）：
  · 盘底/盘心这类**地标**量法，在帧 3~6 会被那道弧的宽亮段冒充 ⇒ 量出来的"盘挪了 7 像素"
    是假的。证据：按它钉完再叠，盘糊成两层；而**照原版公式**叠，盘的轮廓是锐的。
  · 所以这次不比"边在哪"，直接比**花纹本身**：第 0 帧那块盘上的亮条图案，
    在第 i 帧里到底出现在哪个位置。花纹是高频结构，气与弧都是糊的 ⇒ 相关峰必须很尖。

预测位（这是本题的全部）：原版 `CharacterItem.setOrigin():53-60` 就是 `bmp = −原点`，
  所以"照原版摆"时，第 i 帧的盘应当出现在
      预测左上 = (原点x_i + (阵0左 − 原点x_0), 原点y_i + (阵0顶 − 原点y_0))
  我在这格附近 ±12 搜最佳 RGB 匹配：
      偏移 (0,0) ⇒ 原版公式本来就把九帧的盘摆在同一处 ⇒ **该照原版摆，不该自己加补偿**
      偏移非 0   ⇒ 盘真的挪了，挪多少就是那个数 ⇒ 补偿照它加，且必须逐帧对上

四条对照（任一坏就不许出结论）：
  ① 第 0 帧配自己 ⇒ 偏移 (0,0)、平均色差 0；
  ② 造一张整幅挪 (+5,−3) 的假帧 ⇒ 必须配回 (+5,−3)（证明这把尺子认得位移）；
  ③ 峰必须**尖**：最佳格的色差要比周边 8 邻格明显低，否则"找到"是假的；
  ④ 阴性：拿一块**只有气没有盘**的模板去配 ⇒ 平均色差必须显著高（证明色差这个数分得开"是盘/不是盘"）。

用法：python 开发工具/配盘定基准.py      产物：测试/截图/打坐/配盘定基准.txt
"""
import io
import json
import os
import sys

import numpy as np
from PIL import Image

工程 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
表路 = os.path.join(工程, "数据", "界面", "打坐光环.json")
出目 = os.path.join(工程, "测试", "截图", "打坐")
搜 = 12
# 第 0 帧那块盘的**画布**范围（长横条 ≥25 那版量到的连续带，行 33~53 / 列 32~121）
阵0 = {"顶": 33, "底": 53, "左": 32, "右": 121}


def 读(i):
    表 = json.load(io.open(表路, encoding="utf-8"))
    帧 = 表["帧"][i]
    像 = Image.open(os.path.join(工程, 帧["文件"][len("res://"):])).convert("RGBA")
    return 帧, np.asarray(像, dtype=np.int16)


def 色差(模, 模掩, 色, 顶, 左):
    """模板(高×宽×4) 与 色 图在 (顶,左) 处那块的平均/最大色差，只数模掩为 True 的像素。"""
    高, 宽 = 模掩.shape
    底 = 色[顶:顶 + 高, 左:左 + 宽]
    if 底.shape[:2] != 模掩.shape:
        return 999.0, 999.0
    差 = np.abs(底[..., :3] - 模[..., :3]).max(axis=2)
    数 = int(模掩.sum())
    return float(差[模掩].sum()) / 数, float(差[模掩].max())


def 找(模, 模掩, 色, 预顶, 预左):
    最 = None
    图 = {}
    for dy in range(-搜, 搜 + 1):
        for dx in range(-搜, 搜 + 1):
            平, 峰 = 色差(模, 模掩, 色, 预顶 + dy, 预左 + dx)
            图[(dy, dx)] = 平
            if 最 is None or 平 < 最[2]:
                最 = (dx, dy, 平, 峰)
    return 最, 图


def main():
    表 = json.load(io.open(表路, encoding="utf-8"))
    帧表 = 表["帧"]
    色们 = [读(i)[1] for i in range(len(帧表))]
    原0x, 原0y = int(帧表[0]["原点x"]), int(帧表[0]["原点y"])
    模 = 色们[0][阵0["顶"]:阵0["底"] + 1, 阵0["左"]:阵0["右"] + 1]
    模掩 = 模[..., 3] > 90
    行 = []

    def 写(s):
        行.append(s)
        print(s)

    写("模板 = 第 0 帧的盘（画布行 %d~%d、列 %d~%d，%d 个 alpha>90 的像素）"
        % (阵0["顶"], 阵0["底"], 阵0["左"], 阵0["右"], int(模掩.sum())))

    # 对照①
    最, _ = 找(模, 模掩, 色们[0], 阵0["顶"], 阵0["左"])
    写("[对照①] 第 0 帧配自己 ⇒ 偏移(%d,%d) 平均色差 %.1f %s"
        % (最[0], 最[1], 最[2], "OK" if (最[0], 最[1]) == (0, 0) and 最[2] < 1 else "★坏"))
    # 对照②：造一张整幅挪过的假帧
    挪 = (5, -3)
    高0, 宽0 = 色们[0].shape[0], 色们[0].shape[1]
    假 = np.zeros((高0 + 40, 宽0 + 40, 4), dtype=np.int16)
    假[20 + 挪[1]:20 + 挪[1] + 高0, 20 + 挪[0]:20 + 挪[0] + 宽0] = 色们[0]
    最, _ = 找(模, 模掩, 假, 阵0["顶"] + 20, 阵0["左"] + 20)
    写("[对照②] 造一张整幅挪 %s 的假帧 ⇒ 配回偏移(%d,%d) 平均色差 %.1f %s"
        % (挪, 最[0], 最[1], 最[2], "OK" if (最[0], 最[1]) == 挪 and 最[2] < 1 else "★坏：这把尺子认不出位移"))
    # 对照④：阴性 —— 模板换成"只有气"的一块（第 4 帧上半，盘以外）
    色4 = 色们[4]
    模气 = 色4[8:8 + 21, 60:60 + 90]
    模气掩 = 模气[..., 3] > 90
    平气, 峰气 = 色差(模气, 模气掩, 色4, 阵0["顶"] + int(帧表[4]["原点y"]) - 原0y,
                      阵0["左"] + int(帧表[4]["原点x"]) - 原0x)
    写("[对照④] 阴性：拿第 4 帧上半'只有气'的一块当模板，去配它自己预测位 ⇒ 平均色差 %.1f"
        "（这块本来就该 0，所以真正的阴性是下面这条：拿气块去配第 0 帧的盘位）" % 平气)
    平气2, _ = 色差(模气, 模气掩, 色们[0], 阵0["顶"], 阵0["左"])
    写("       气块 vs 第 0 帧的盘位 ⇒ 平均色差 %.1f ⇒ 与下面各帧的数比："
        "如果各帧都远小于这个数，说明配到的确实是盘、不是随便一块糊的" % 平气2)

    写("")
    写("帧  原点      预测左上(照原版公式)   最佳偏移(dx,dy)  平均色差  峰值色差  周边8邻最低  峰尖?")
    结 = []
    for i, 帧 in enumerate(帧表):
        原x, 原y = int(帧["原点x"]), int(帧["原点y"])
        预顶 = 阵0["顶"] + (原y - 原0y)
        预左 = 阵0["左"] + (原x - 原0x)
        if 预顶 < 0 or 预左 < 0 or 预顶 + 模.shape[0] > 色们[i].shape[0] or 预左 + 模.shape[1] > 色们[i].shape[1]:
            写("%d  预测位出画布 ⇒ 跳过（%d,%d）" % (i, 预顶, 预左))
            continue
        最, 图 = 找(模, 模掩, 色们[i], 预顶, 预左)
        邻 = min(图[(dy, dx)] for (dy, dx) in 图
                 if max(abs(dy - 最[1]), abs(dx - 最[0])) == 1) if 最 else 999
        写("%d  %4d,%-4d  (%4d,%4d)          (%+3d,%+3d)     %6.1f   %6.1f    %6.1f     %s"
            % (i, 原x, 原y, 预顶, 预左, 最[0], 最[1], 最[2], 最[3], 邻,
               "尖" if 邻 > 最[2] + 8 else "不尖★"))
        结.append({"帧": i, "偏移x": 最[0], "偏移y": 最[1], "平均色差": round(最[2], 1),
                   "峰值色差": round(最[3], 1), "周边最低": round(邻, 1)})
    写("")
    写("⇒ 读法：偏移全 0 ⇒ **原版公式自己就把九帧的盘摆在同一处**，我们不该再加任何补偿；"
        "偏移非 0 ⇒ 那是盘真的挪了，补偿照这个数加（不是照'最后一个不透明像素行'加）。")
    os.makedirs(出目, exist_ok=True)
    io.open(os.path.join(出目, "配盘定基准.txt"), "w", encoding="utf-8", newline="\n")\
        .write("\n".join(行) + "\n")
    json.dump(结, io.open(os.path.join(出目, "配盘定基准.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
