def 节点行(正文, 路径, 根名):
    """按 Godot 的 parent= 写法拼出该节点的 [node ...] 行前缀。
    根节点没有 parent= 属性；直接子节点是 `parent="."`；再往下是完整相对路径。"""
    名 = 路径.split("/")[-1]
    父 = "/".join(路径.split("/")[:-1])
    if 路径 == 根名:
        后缀 = ""
    elif not 父:
        后缀 = ' parent="."'
    else:
        后缀 = ' parent="%s"' % 父
    正 = r'\[node name="%s" type="[^"]+"%s' % (re.escape(名), re.escape(后缀))
    if re.search(r"^" + 正, 正文, re.M) is None:
        return None
    return 正


