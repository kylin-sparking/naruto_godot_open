# -*- coding: utf-8 -*-
"""量「八卦阵」在九帧里各自画在哪 —— 用户 2026-10-13 提的基准：
**以角色脚下那块阵为准，九帧的阵互相重合，就不许飘。**

为什么还要再量一遍（现有代码钉的是「最后一个不透明像素行」= 阵的下沿一行）：
  一条边只管竖直，也**看不出阵有没有被画成不同大小**。整块阵当模板去配，
  才能同时给出 水平/竖直 两个位移 + 一个「配得上吗」的分数。

量法（第 2 版；第 1 版被自己的对照①当场判废 —— 模板原点算成了画布原点，
      于是"自己配自己"报出 (29,23)，见 阵对齐.txt 的历史）：
  · 模板 = **第 0 帧**里那块阵的亮青包围盒（第 0 帧整幅 150×79，几乎只有阵 +
    一点弧，没有那团往上撑的气 ⇒ 拿它当模板最干净）。
    亮 = alpha>90 且 (蓝+绿)/2 − 红 > 18。
  · 配准 = **整幅搜**（不是 ±30 局部窗）：用 FFT 相关一次算出"模板左上角落在
    每个画布位置时的命中数"，分数 = 命中数 / 模板亮像素数。
    ⚠ 这个分数只数「模板亮的地方在目标里也亮」⇒ 上面压了别的东西（气珠、弧）
    只会**多加**亮像素、不会把阵的亮条弄没 ⇒ 遮挡不会把分数压低。
    ⚠ 不拿"宽度"当判据（前两轮按宽度找环都被那团气污染、结果顶到窗口边界，
    见 量打坐环心2.py 的作废说明）。
  · 三条对照，缺一条这次量法就不许用：
      ① 第 0 帧自己配自己 ⇒ 必须 (0,0)、分数 1.000；
      ② 造两张"整幅被挪过 (+7,0) / (0,+5)"的假帧 ⇒ 必须原样配回来；
      ③ 把第 0 帧的阵整块挖掉只剩气 ⇒ 分数必须明显低（否则"分数"没意义）。

用法：python 开发工具/量八卦阵对齐.py
产物：测试/截图/打坐/阵对齐.txt（人看）+ 阵对齐.json（每条含 阵x/阵y/分）
"""
import io
import json
import os
import sys

import numpy as np
from PIL import Image

工程 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
表路 = os.path.join(工程, "数据", "界面", "打坐光环.json")
出目 = os.path.join(工程, "测试", "截图", "打坐")


def 亮青(像):
    """→ 高×宽 的 bool 数组：True = 这块是"亮青"（阵上的条与边）。"""
    a = np.asarray(像.convert("RGBA"), dtype=np.int16)
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    return (al > 90) & ((((b + g) / 2.0) - r) > 18)


def 包围(布):
    行 = np.flatnonzero(布.any(axis=1))
    列 = np.flatnonzero(布.any(axis=0))
    if 行.size == 0 or 列.size == 0:
        return None
    return int(列[0]), int(行[0]), int(列[-1]), int(行[-1])


def 配(模板, 布):
    """整幅搜：返回 (最佳左上角落点 x,y, 覆盖率, 交并比 IoU, 次佳覆盖率)。
    落点 = **模板左上角在目标画布上的坐标**，所以"自己配自己"必然 = 模板原本左上角。
    ⚠ 两个分数都要看：覆盖率 = 模板亮的地方在目标里也亮的比例（对遮挡不敏感，
      但目标那一片如果整片都亮会**假满分**）；IoU = 交/并（要求两边形状真的对得上）。
      只有两者都高，才允许说"这是同一块阵被平移"。"""
    模高, 模宽 = 模板.shape
    高, 宽 = 布.shape
    n = float(模板.sum())
    # 补零到 (高+模高, 宽+模宽) 再相关 ⇒ 免掉 FFT 的回绕（右下角那圈会绕到左上）
    画高, 画宽 = 高 + 模高, 宽 + 模宽
    目 = np.zeros((画高, 画宽))
    目[:高, :宽] = 布
    模 = np.zeros((画高, 画宽))
    模[:模高, :模宽] = 模板
    相关 = np.fft.irfft2(np.fft.rfft2(目) * np.conj(np.fft.rfft2(模)), s=(画高, 画宽))
    # 相关[y,x] = Σ 目[y+dy,x+dx]·模板[dy,dx] ⇒ 模板左上角落在 (x,y) 时的命中数
    有 = 相关[:max(0, 高 - 模高 + 1), :max(0, 宽 - 模宽 + 1)]
    分图 = 有 / n
    平 = 分图.ravel()
    序 = np.argsort(平)[::-1]
    最 = np.unravel_index(int(序[0]), 分图.shape)
    次 = float(平[序[1]]) if 序.size > 1 else 0.0
    x, y = int(最[1]), int(最[0])
    块 = 布[y:y + 模高, x:x + 模宽]
    交 = float(np.logical_and(模板, 块).sum())
    并 = float(np.logical_or(模板, 块).sum())
    return x, y, float(平[序[0]]), (交 / 并 if 并 else 0.0), 次


def 色配(模板, 阵左上, 第0阵, 色0, 色i):
    """在"阵对齐"的那个落点上，逐像素比 RGB ⇒ 覆盖 1.000 只说明亮的地方还在，
    **颜色也对得上**才敢说是同一块阵被平移。返回 (同色比例, 平均色差)。
    ⚠ 两块必须各取各的位置：第 0 帧的阵永远从 `第0阵` 裁（第 0 帧只有 79 行高，
      拿目标帧的落点去裁它会裁空、被下面的尺寸自检直接判 0 —— 第一版就栽在这）。"""
    左, 上 = 阵左上
    模高, 模宽 = 模板.shape
    底0 = 色0[第0阵[1]:第0阵[1] + 模高, 第0阵[0]:第0阵[0] + 模宽]
    底i = 色i[上:上 + 模高, 左:左 + 模宽]
    if 底0.shape[:2] != 模板.shape or 底i.shape[:2] != 模板.shape:
        return 0.0, 999.0
    差 = np.abs(底i.astype(np.int16) - 底0.astype(np.int16)).max(axis=2)
    亮 = 模板
    n = int(亮.sum())
    同 = int(((差 <= 24) & 亮).sum())
    return 同 / float(n), float(差[亮].mean())


def main():
    表 = json.load(io.open(表路, encoding="utf-8"))
    帧表 = 表["帧"]
    图们 = []
    for 帧 in 帧表:
        路 = os.path.join(工程, 帧["文件"][len("res://"):])
        像 = Image.open(路).convert("RGBA")
        图们.append((帧, 像, 亮青(像), np.asarray(像.convert("RGB"), dtype=np.uint8)))

    行 = []

    def 写(s):
        行.append(s)
        print(s)

    帧0, 像0, 布0, 色0 = 图们[0]
    高0, 宽0 = 布0.shape
    阵0 = 包围(布0)
    模板 = 布0[阵0[1]:阵0[3] + 1, 阵0[0]:阵0[2] + 1]
    写("第 0 帧的阵（亮青包围盒，画布坐标）= 左%d 上%d 右%d 下%d ⇒ %d×%d 像素；"
        "注册点(%d,%d)、画布 %d×%d"
        % (阵0[0], 阵0[1], 阵0[2], 阵0[3], 阵0[2] - 阵0[0] + 1, 阵0[3] - 阵0[1] + 1,
           int(帧0["原点x"]), int(帧0["原点y"]), 宽0, 高0))
    写("模板亮像素数 = %d（占包围盒 %.1f%%）" % (int(模板.sum()), 100.0 * 模板.sum() / 模板.size))

    # ── 对照①：自己配自己 ⇒ 落点必须 = 阵0 的左上角
    x, y, 分, 交, 次 = 配(模板, 布0)
    写("")
    写("[对照①] 第 0 帧配第 0 帧 ⇒ 落点(%d,%d) 覆盖 %.3f / IoU %.3f（次佳 %.3f）期望落点(%d,%d) %s"
        % (x, y, 分, 交, 次, 阵0[0], 阵0[1],
           "OK" if (x, y) == (阵0[0], 阵0[1]) and 分 > 0.999 else "★坏：量法不可信"))
    # ── 对照②：整幅挪过的假帧 ⇒ 必须原样配回
    for 名, 挪 in (("+7,0", (7, 0)), ("0,+5", (0, 5)), ("-11,+3", (-11, 3))):
        假 = np.zeros((高0 + 40, 宽0 + 40), dtype=bool)
        假[20 + 挪[1]:20 + 挪[1] + 高0, 20 + 挪[0]:20 + 挪[0] + 宽0] = 布0
        x, y, 分, 交, 次 = 配(模板, 假)
        望 = (阵0[0] + 20 + 挪[0], 阵0[1] + 20 + 挪[1])
        写("[对照②] 造一张整幅挪 %s 的假帧 ⇒ 配出落点(%d,%d) 覆盖 %.3f，期望(%d,%d)%s"
            % (名, x, y, 分, 望[0], 望[1], "OK" if (x, y) == 望 and 分 > 0.999 else "★坏"))
    # ── 对照③：挖掉阵只剩气 ⇒ 分数必须明显低
    挖 = 布0.copy()
    挖[阵0[1]:阵0[3] + 1, 阵0[0]:阵0[2] + 1] = False
    x, y, 分, 交, 次 = 配(模板, 挖)
    写("[对照③] 拿「挖掉阵、只剩气」的第 0 帧去配 ⇒ 最高覆盖 %.3f（落点 %d,%d，"
        "要远低于 1.0 才说明分数有用）%s" % (分, x, y, "OK" if 分 < 0.6 else "★坏"))

    # ── 正文：逐帧整幅配
    写("")
    写("帧  画布        原点       阵左上角落点   相对第0帧(dx,dy)  覆盖   IoU  同色比例 平均色差  "
        "裸摆偏差(x,y)  钉阵之后")
    结 = []
    基准 = None
    基x = None
    for i, (帧, 像, 布, 色) in enumerate(图们):
        高, 宽 = 布.shape
        if i == 0:
            x, y, 分, 交, 次 = 阵0[0], 阵0[1], 1.0, 1.0, 0.0
        else:
            x, y, 分, 交, 次 = 配(模板, 布)
        同, 差 = 色配(模板, (x, y), (阵0[0], 阵0[1]), 色0, 色)
        原x, 原y = int(帧["原点x"]), int(帧["原点y"])
        if 基准 is None:
            基准 = y - 原y
            基x = x - 原x
        写("%d  %dx%-6d %4d,%-4d   %4d,%-4d     %+4d %+4d      %.3f %.3f  %5.1f%%  %5.1f   "
          "(%+d,%+d)   (0,0)"
          % (i, 宽, 高, 原x, 原y, x, y, x - 阵0[0], y - 阵0[1], 分, 交,
             100.0 * 同, 差, (x - 原x) - 基x, (y - 原y) - 基准))
        结.append({"帧": i, "阵x": x, "阵y": y, "dx": x - 阵0[0], "dy": y - 阵0[1],
                   "覆盖": round(分, 3), "IoU": round(交, 3), "同色": round(同, 4),
                   "裸摆偏差x": (x - 原x) - 基x, "裸摆偏差y": (y - 原y) - 基准})
    写("")
    写("⇒ 「裸摆偏差」= 什么都不钉、只照 AS3 `CharacterItem.setOrigin()` 的 −原点 摆，"
        "阵会挪几个像素（正=偏下/偏右）。这一列就是**素材自己**的沉浮，钉阵之后全为 (0,0)。")
    写("⇒ 覆盖≈1 **且同色比例≈100%** 才敢钉：覆盖只说明亮的地方还在，"
        "同色才说明是同一块阵被平移、不是碰巧被气糊满。")
    os.makedirs(出目, exist_ok=True)
    io.open(os.path.join(出目, "阵对齐.txt"), "w", encoding="utf-8", newline="\n")\
        .write("\n".join(行) + "\n")
    json.dump(结, io.open(os.path.join(出目, "阵对齐.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
